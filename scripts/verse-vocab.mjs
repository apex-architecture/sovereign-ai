/**
 * Generates the shared vocabulary artefacts from one source of truth.
 *   node --experimental-strip-types scripts/verse-vocab.mjs            write the artefacts
 *   node --experimental-strip-types scripts/verse-vocab.mjs --check    prove they are current
 *
 * Two things are written:
 *
 *   verse-site/vocabulary.js   the machine-readable contract. Any integrator, any tool, any
 *                              third-party repo can read it and know the name of every room.
 *   verse-site/shell.js        the public rail's navigation, injected between the markers.
 *
 * The nav used to be a hand-written array in shell.js while the app's nav was a hand-written
 * array in a React file, and the two drifted apart until the same room had two names. Now the
 * arrays are generated from src/lib/apex/vocabulary.ts, and CI fails if what is on disk no
 * longer matches what the source says.
 *
 * --check changes nothing and fails loudly. That is what CI runs, and what anyone can run
 * before they believe the two ends still agree.
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { siteDir } from "./site-dir.mjs";

const CHECK = process.argv.includes("--check");
const ROOT = path.resolve(import.meta.dirname, "..");
const SITE = siteDir(ROOT);
const START = "/* VOCAB-NAV:START */";
const END = "/* VOCAB-NAV:END */";

/** The rail's home page is written as index.html in the app and published as studio.html. */
const HOME = path.basename(SITE) === "docs" ? "studio.html" : "studio.html";
const railHref = (href) => href.replace(/^index\.html/, HOME);

/** Decorative glyphs for the public rail sidebar. Names come from the vocabulary, never here. */
const GLYPH = {
  studio: "⌂", create: "✚", director: "◑", oracle: "◌", mission: "✦",
  theater: "◐", library: "▤", connect: "⌁", registry: "◈", pipeline: "≡",
  opensource: "✧", projects: "▣", foreman: "◔", verify: "✓", passport: "◉",
  rights: "§", console: "▮", cost: "◧", broadcast: "➤", guide: "✎",
  nominate: "✍", beta: "⊙", legal: "⚖", academy: "⌸", community: "☷", settings: "⚒",
};

const url = (rel) => pathToFileURL(path.resolve(ROOT, rel)).href;
const { BRAND, GROUPS, CONCEPTS, CONCEPT_BY_ID, APP_PRIMARY, APP_SECONDARY } =
  await import(url("src/lib/apex/vocabulary.ts"));

const problems = [];
const fail = (msg) => problems.push(msg);

/* ---------------------------------------------------------------- the vocabulary itself */

const ids = new Set();
const labels = new Map();
for (const c of CONCEPTS) {
  if (ids.has(c.id)) fail(`duplicate concept id "${c.id}"`);
  ids.add(c.id);
  if (labels.has(c.label)) fail(`"${c.label}" is used by both "${labels.get(c.label)}" and "${c.id}"`);
  labels.set(c.label, c.id);
  if (!GROUPS.includes(c.group)) fail(`concept "${c.id}" has unknown group "${c.group}"`);
  if (!c.purpose || c.purpose.length < 8) fail(`concept "${c.id}" has no useful purpose line`);
}

for (const id of [...APP_PRIMARY, ...APP_SECONDARY]) {
  const c = CONCEPT_BY_ID.get(id);
  if (!c) { fail(`app nav lists "${id}" which is not a concept`); continue; }
  if (!c.app) fail(`app nav lists "${id}" which has no app route`);
}
const overlap = APP_PRIMARY.filter((id) => APP_SECONDARY.includes(id));
if (overlap.length) fail(`app nav lists ${overlap.join(", ")} in both tiers`);

/* ---------------------------------------------------------------- the surfaces exist */

for (const c of CONCEPTS) {
  if (c.app) {
    const file = c.app === "/" ? "index.tsx" : `${c.app.replace(/^\//, "")}.tsx`;
    if (!existsSync(path.join(ROOT, "src/routes", file))) {
      fail(`concept "${c.id}" points at app route ${c.app} but src/routes/${file} does not exist`);
    }
  }
  if (c.rail) {
    const file = c.rail.split("#")[0];
    if (!existsSync(path.join(SITE, file))) {
      fail(`concept "${c.id}" points at rail page ${file} but it does not exist in ${path.basename(SITE)}/`);
    }
  }
}

/* ---------------------------------------------------------------- the generated nav */

const missingGlyph = CONCEPTS.filter((c) => !GLYPH[c.id]).map((c) => c.id);
if (missingGlyph.length) fail(`no rail glyph for ${missingGlyph.join(", ")}`);

const navItems = (group) =>
  CONCEPTS.filter((c) => c.group === group && (c.rail || !c.built)).map((c) => {
    const ico = GLYPH[c.id];
    return c.built
      ? `      { id: "${c.id}", href: "${railHref(c.rail)}", label: "${c.label}", ico: "${ico}" },`
      : `      { id: "${c.id}", off: true, label: "${c.label}", ico: "${ico}" },`;
  });

const navBlock = [
  START,
  "  // Generated by scripts/verse-vocab.mjs from src/lib/apex/vocabulary.ts. Do not hand-edit:",
  "  // the app nav and this nav are the same list, and CI fails when they stop matching.",
  "  const NAV = [",
  ...GROUPS.map((g) => {
    const items = navItems(g);
    if (!items.length) return null;
    return [`    { group: "${g}", items: [`, ...items, "    ]},"];
  }).filter(Boolean).flat(),
  "  ];",
  END,
].join("\n");

const shellPath = path.join(SITE, "shell.js");
const shell = readFileSync(shellPath, "utf8");
const startAt = shell.indexOf(START);
const endAt = shell.indexOf(END);
if (startAt === -1 || endAt === -1) {
  fail(`${shellPath} has no VOCAB-NAV markers — the generator cannot place the nav`);
} else {
  const nextShell = shell.slice(0, startAt) + navBlock + shell.slice(endAt + END.length);
  if (nextShell !== shell) {
    if (CHECK) fail(`${path.basename(SITE)}/shell.js nav is out of date — run scripts/verse-vocab.mjs`);
    else { writeFileSync(shellPath, nextShell); console.log(`  shell.js  nav regenerated (${CONCEPTS.length} concepts)`); }
  } else {
    console.log("  shell.js  nav already current");
  }
}

const contract = `/* Generated by scripts/verse-vocab.mjs from src/lib/apex/vocabulary.ts. Do not hand-edit. */
window.APEX_VOCAB = ${JSON.stringify(
  {
    brand: BRAND,
    groups: GROUPS,
    concepts: CONCEPTS.map((c) => ({
      id: c.id, label: c.label, purpose: c.purpose, group: c.group,
      app: c.app, rail: c.rail ? railHref(c.rail) : null, built: c.built,
    })),
    appNav: { primary: APP_PRIMARY, secondary: APP_SECONDARY },
  },
  null,
  2,
)};
`;
const contractPath = path.join(SITE, "vocabulary.js");
if (!existsSync(contractPath)) {
  if (CHECK) fail(`${path.basename(SITE)}/vocabulary.js is missing — run scripts/verse-vocab.mjs`);
  else { writeFileSync(contractPath, contract); console.log(`  vocabulary.js  ${CONCEPTS.length} concepts written`); }
} else if (readFileSync(contractPath, "utf8") !== contract) {
  if (CHECK) fail(`${path.basename(SITE)}/vocabulary.js is out of date — run scripts/verse-vocab.mjs`);
  else { writeFileSync(contractPath, contract); console.log(`  vocabulary.js  ${CONCEPTS.length} concepts rewritten`); }
} else {
  console.log("  vocabulary.js  already current");
}

/* ---------------------------------------------------------------- verdict */

if (problems.length) {
  console.error("\nVOCAB FAILED");
  for (const p of problems) console.error("  " + p);
  process.exit(1);
}
console.log(`\nVOCAB OK — ${CONCEPTS.length} concepts, one name per room, on both ends.`);
