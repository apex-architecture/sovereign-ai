/**
 * Generates the Film Verse site data from the real registry.
 *   node --experimental-strip-types scripts/verse-data.mjs
 *
 * Nothing here is typed by hand. Every figure the public site prints is counted from
 * src/lib/apex in this run, and the source hash lets anyone prove which rows produced it.
 */

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { siteDir } from "./site-dir.mjs";

const APEX = path.resolve("src/lib/apex");
const SITE = siteDir();
const url = (rel) => pathToFileURL(path.join(APEX, rel)).href;

const { MASTER_REGISTRY, categoriesCovered, categoriesEmpty, rowsWithoutExit, duplicateNames, licenceReviewNeeded } =
  await import(url("index.ts"));
const { CATEGORIES } = await import(url("schema.ts"));
const { CONNECTIONS, STAGE_CONNECTION, depthCount, stageCoverage } = await import(url("connection.ts"));
const { MODULES } = await import(url("modules.ts"));

const SOURCE_FILES = [
  "catalog/creative-visual.ts",
  "catalog/creative-time.ts",
  "catalog/creative-sound-design.ts",
  "catalog/intelligence.ts",
  "catalog/platform-infra.ts",
  "catalog/economy-reach.ts",
  "connection.ts",
  "modules.ts",
];
const hash = createHash("sha256");
for (const f of SOURCE_FILES) hash.update(readFileSync(path.join(APEX, f)));

const depths = depthCount();
const cover = stageCoverage();
const rows = MASTER_REGISTRY;

const cleared = rows.filter((r) => r.licenseVerified && r.commercialUse === "yes").length;
const awaiting = rows.filter((r) => !r.licenseVerified || r.commercialUse === "unverified").length;
const atZero = rows.filter((r) => r.cost === "$0").length;
const onMachine = rows.filter((r) => r.localExecution).length;

const byCategory = {};
for (const r of rows) byCategory[r.category] = (byCategory[r.category] ?? 0) + 1;

const depthOf = Object.fromEntries(CONNECTIONS.map((c) => [c.toolId, c.depth]));
const stages = Object.entries(STAGE_CONNECTION).map(([id, tools]) => ({
  id,
  tools,
  best: tools.length === 0 ? "none" : tools.map((t) => depthOf[t]).sort()[0] ?? "none",
}));

const data = {
  generatedAt: new Date().toISOString(),
  sourceHash: hash.digest("hex"),
  stats: {
    rows: rows.length,
    categoriesTotal: CATEGORIES.length,
    categoriesCovered: categoriesCovered(rows).length,
    categoriesEmpty: categoriesEmpty(rows),
    clearedForClientWork: cleared,
    awaitingLicenceRead: awaiting,
    rowsWithoutExit: rowsWithoutExit(rows).length,
    duplicates: duplicateNames(rows).length,
    reviewQueue: licenceReviewNeeded(rows).length,
    runsAtZero: atZero,
    runsOnYourMachine: onMachine,
  },
  depths,
  coverage: cover,
  connections: CONNECTIONS,
  stages,
  modules: MODULES.map((m) => ({
    id: m.id,
    name: m.name,
    purpose: m.purpose,
    layer: m.layer,
    status: m.status,
    route: m.route ?? null,
    engine: m.engine,
    dependsOn: m.dependsOn,
  })),
  rows: rows.map((r) => ({
    n: r.name,
    c: r.category,
    l: r.license,
    cu: r.commercialUse,
    rd: r.redistribution,
    sh: r.selfHosting,
    le: r.localExecution,
    co: r.cost,
    pr: r.priority,
    im: r.integrationMethod,
    cap: r.capability,
    ex: r.replacementOptions,
    v: r.licenseVerified,
    u: r.officialUrl || r.sourceRepository || "",
  })),
};

mkdirSync(SITE, { recursive: true });
const out =
  `/* GENERATED by scripts/verse-data.mjs — do not edit. Regenerate, never hand-type a number. */\n` +
  `/* VERSE_BUILD is the identity of the inputs; the guard compares it against the live rail to prove a build shipped. */\n` +
  `const VERSE_BUILD = "${data.sourceHash.slice(0, 16)}";\n` +
  `window.APEX_VERSE = ${JSON.stringify(data)};\n`;
writeFileSync(path.join(SITE, "data.generated.js"), out);

/**
 * The same global without the two heavy tables. A page that counts rows or draws the map must load
 * the full file; a page that only prints the measured facts loads this one and ships ~1% of the
 * bytes. The shape is identical on purpose — `rows: []` is a real empty array, not a missing field,
 * so a page that wrongly reaches for the registry gets an honest zero instead of a crash.
 */
const light = { ...data, rows: [], modules: [] };
writeFileSync(
  path.join(SITE, "data.shell.js"),
  `/* GENERATED by scripts/verse-data.mjs — the registry facts without the registry tables. Do not edit. */\n` +
    `const VERSE_BUILD = "${data.sourceHash.slice(0, 16)}";\n` +
    `window.APEX_VERSE = ${JSON.stringify(light)};\n`,
);

const s = data.stats;
console.log(
  `rows=${s.rows} categories=${s.categoriesCovered}/${s.categoriesTotal} cleared=${s.clearedForClientWork}` +
    ` awaiting=${s.awaitingLicenceRead} noExit=${s.rowsWithoutExit} dupes=${s.duplicates}` +
    ` atZero=${s.runsAtZero} onMachine=${s.runsOnYourMachine}` +
    ` depths=${depths.drivable}/${depths["file-exchange"]}/${depths["portal-only"]}/${depths["not-yet"]}` +
    ` stages=${cover.wired}/${cover.total} empty=${cover.empty.join(",") || "none"}`,
);
console.log(`sourceHash=${data.sourceHash.slice(0, 16)}… bytes=${out.length}`);
