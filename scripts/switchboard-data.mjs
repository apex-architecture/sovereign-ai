/**
 * Generates the switchboard data the public Connect page reads.
 *   node --experimental-strip-types scripts/switchboard-data.mjs
 *
 * Nothing here is typed by hand. Every count the page prints is resolved from src/lib/apex in this
 * run, and the source hash lets anyone prove which rows produced it. The page must never claim a
 * stage is connected that this run did not resolve as connected.
 */

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { siteDir } from "./site-dir.mjs";

const APEX = path.resolve("src/lib/apex");
const SITE = siteDir();
const url = (rel) => pathToFileURL(path.join(APEX, rel)).href;

const { CONNECTORS } = await import(url("connectors.ts"));
const { PLUGS, plugCount, reachCount, pluggedConnectors, liveOnPages, unverifiedLicences } =
  await import(url("plugs.ts"));
const { STAGES, resolveAll, pipelineCoverage, zeroPlugStages } = await import(url("switchboard.ts"));

const SOURCE_FILES = ["connectors.ts", "plugs.ts", "switchboard.ts"];
const hash = createHash("sha256");
for (const f of SOURCE_FILES) hash.update(readFileSync(path.join(APEX, f)));

/** The four connection states a visitor can compare, resolved rather than asserted. */
const SCENARIOS = [
  { id: "nothing", label: "Nothing plugged in", plugged: {} },
  { id: "rig", label: "Your own rig", plugged: { rig: "http://127.0.0.1:8188" } },
  { id: "cloud", label: "Your own cloud key", plugged: { cloud: true } },
  { id: "all", label: "Rig, bridge and key", plugged: { rig: "http://127.0.0.1:8188", bridge: "http://127.0.0.1:8787", cloud: true } },
];

const data = {
  generatedAt: new Date().toISOString(),
  sourceHash: hash.digest("hex").slice(0, 16),
  connectorCount: CONNECTORS.length,
  plugs: PLUGS,
  plugCount: plugCount(),
  reachCount: reachCount(),
  stages: STAGES,
  connectors: pluggedConnectors().map((p) => ({
    provider: p.connector.provider,
    product: p.connector.product,
    family: p.connector.family,
    plug: p.plug,
    reach: p.reach,
    docsUrl: p.connector.docsUrl,
    apiBaseUrl: p.connector.apiBaseUrl,
    usageCharge: p.connector.usageCharge,
    licenceTerms: p.connector.licenceTerms,
    securityStatus: p.connector.securityStatus,
    exit: p.connector.replacementProvider,
    lastTested: p.connector.lastTested,
  })),
  liveOnPages: liveOnPages().map((p) => p.connector.provider),
  zeroPlugStages: zeroPlugStages().map((s) => s.id),
  unverifiedLicences: unverifiedLicences(),
  scenarios: SCENARIOS.map((s) => ({
    id: s.id,
    label: s.label,
    coverage: pipelineCoverage(s.plugged),
    resolved: resolveAll(s.plugged).map((r) => ({
      id: r.stage.id,
      connected: r.connected,
      chosen: r.chosen ? r.chosen.provider : null,
      says: r.says,
      routes: r.routes.map((x) => ({ provider: x.provider, plug: x.plug, reach: x.reach, available: x.available, needs: x.needs })),
    })),
  })),
};

const out = `/* GENERATED by scripts/switchboard-data.mjs — do not edit. */\nwindow.APEX_SWITCHBOARD = ${JSON.stringify(data)};\n`;
writeFileSync(path.join(SITE, "switchboard.data.js"), out);

const nothing = data.scenarios[0].coverage;
const all = data.scenarios[3].coverage;
console.log(
  `switchboard: ${data.connectorCount} connectors, ${PLUGS.length} plugs, ${STAGES.length} stages\n` +
    `  nothing plugged in: ${nothing.connected}/${nothing.total} — ${data.zeroPlugStages.join(", ")}\n` +
    `  everything plugged in: ${all.connected}/${all.total}\n` +
    `  live from static hosting: ${data.liveOnPages.join(", ")}\n` +
    `  written: ${path.join(SITE, "switchboard.data.js")} (${(Buffer.byteLength(out) / 1024).toFixed(1)} KB)`,
);