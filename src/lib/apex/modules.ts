export const MODULE_BY_ID: Record<string, ApexModule> = Object.fromEntries(
  MODULES.map((m) => [m.id, m]),
);

export function modulesByLayer(layer: Layer): ApexModule[] {
  return MODULES.filter((m) => m.layer === layer);
}

/** Everything that must be finished before the first paying studio can deliver a package. */
export const FOUNDATION_SET = [
  "core",
  "psi",
  "ledger",
  "passport",
  "verify",
  "licenseguard",
  "registry",
  "connect",
];

export function foundationGap(): string[] {
  return FOUNDATION_SET.filter((id) => MODULE_BY_ID[id].status !== "live").map(
    (id) => `${id} (${MODULE_BY_ID[id].status})`,
  );
}
